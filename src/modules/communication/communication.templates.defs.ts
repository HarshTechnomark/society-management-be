const emgTexts = (head: string): ChannelTexts => ({
  inAppTitle: `{{prefix}}${head}: {{title}}`,
  inAppBody: '{{message}}',
  pushTitle: `{{prefix}}${head}: {{title}}`,
  pushBody: '{{message}}',
  smsBody: `{{prefix}}${head}: {{title}}. {{smsMessage}} {{link}}`,
  smsDltCategory: 'TRANSACTIONAL',
  whatsappTemplateName: 'emergency_alert',
  whatsappCategory: 'UTILITY',
  whatsappParams: ['title', 'message'],
});
const hi = (t: string): ChannelTexts => ({
  inAppTitle: t,
  inAppBody: '{{message}}',
  pushTitle: t,
  pushBody: '{{message}}',
  smsBody: `${t}. {{link}}`,
});

