/**
 * Section 10.1: the templates owned by module 16, plus the ones it registers for module 25 (`resident.*`) and module 24 (`reports.*`).
 * Real `TemplateDefinition`s with `{{placeholders}}`; 16.4's platform editor edits the text, code owns the metadata (BR-16-50).
 * Drills prefix every channel text with `{{prefix}}` ("DRILL: " or empty, BR-16-37).
 */
const s = (maxLength = 60, required = true) => ({ type: 'string' as const, required, maxLength });
const num = (required = true) => ({ type: 'number' as const, required });
const url = (required = false) => ({ type: 'url' as const, required });
const dt = (required = false) => ({ type: 'datetime' as const, required });

function def(
  key: string,
  category: TemplateCategory,
  deliveryClass: DeliveryClass,
  defaultChannels: Channel[],
  variables: VariablesSchema,
  sample: Record<string, unknown>,
  text: ChannelTexts,
  o: {
    allowed?: Channel[];
    deepLink?: string;
    countsTowardLimit?: boolean;
    scope?: 'USER' | 'SOCIETY';
    hi?: ChannelTexts;
    mr?: ChannelTexts;
  } = {},
): TemplateDefinition {
  const allowed = new Set<Channel>([...defaultChannels, 'IN_APP', ...(o.allowed ?? [])]);
  if (deliveryClass === 'SAFETY' || deliveryClass === 'TRANSACTIONAL') allowed.add('SMS');
  return {
    key,
    scope: o.scope ?? 'SOCIETY',
    category,
    deliveryClass,
    defaultChannels,
    allowedChannels: [...allowed],
    variables,
    sample,
    countsTowardLimit: o.countsTowardLimit ?? true,
    deepLink: o.deepLink,
    text: { 'en-IN': text, ...(o.hi ? { 'hi-IN': o.hi } : {}), ...(o.mr ? { 'mr-IN': o.mr } : {}) },
  };
}

