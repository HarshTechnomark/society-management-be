import {
  DataTypes,
  Model,
  type CreationOptional,
  type InferAttributes,
  type InferCreationAttributes,
  type Sequelize,
} from 'sequelize';
import { dateColumn, fkColumn, idColumn, timestampColumns } from './_columns';

export const UNIT_TYPES = ['FLAT', 'SHOP', 'OFFICE', 'PARKING_ONLY'] as const;
export type UnitType = (typeof UNIT_TYPES)[number];
/** BR-08-20: the types that count against `limit.flats`. */
export const COUNTABLE_UNIT_TYPES = ['FLAT', 'SHOP', 'OFFICE'] as const;
export const BHK_VALUES = [
  'STUDIO',
  '1RK',
  '1BHK',
  '1_5BHK',
  '2BHK',
  '2_5BHK',
  '3BHK',
  '3_5BHK',
  '4BHK',
  '5BHK_PLUS',
] as const;
export type Bhk = (typeof BHK_VALUES)[number];

/**
 * Module 08 section 7.2. Areas and the share are DECIMAL columns that Sequelize returns as strings ("1150.000"), which is
 * also how the API sends them. `activeNumberKey` and `activeLabelKey` are generated by MySQL and not mapped here.
 */
export class Unit extends Model<InferAttributes<Unit>, InferCreationAttributes<Unit>> {
  declare id: CreationOptional<number>;
  declare societyId: number;
  declare buildingId: number;
  declare unitNumber: string;
  declare label: string;
  declare floor: number;
  declare positionOnFloor: number | null;
  declare unitType: UnitType;
  declare bhk: Bhk | null;
  declare carpetAreaSqft: string | null;
  declare builtUpAreaSqft: string | null;
  declare superBuiltUpAreaSqft: string | null;
  declare areaSqft: string | null;
  declare undividedSharePct: string | null;
  declare isBillable: boolean;
  declare possessionDate: string | null;
  declare notes: string | null;
  declare status: 'ACTIVE' | 'ARCHIVED';
  declare archivedAt: Date | null;
  declare archivedReason: string | null;
  declare archivedBy: number | null;
  declare version: number;
  declare createdBy: number | null;
  declare updatedBy: number | null;
  declare createdAt: Date | undefined;
  declare updatedAt: Date | undefined;

  static initModel(sequelize: Sequelize): void {
    Unit.init(
      {
        id: idColumn,
        societyId: fkColumn(false),
        buildingId: fkColumn(false),
        unitNumber: { type: DataTypes.STRING(20), allowNull: false },
        label: { type: DataTypes.STRING(27), allowNull: false },
        floor: { type: DataTypes.SMALLINT, allowNull: false },
        positionOnFloor: { type: DataTypes.TINYINT.UNSIGNED, allowNull: true, defaultValue: null },
        unitType: { type: DataTypes.STRING(20), allowNull: false, defaultValue: 'FLAT' },
        bhk: { type: DataTypes.STRING(10), allowNull: true, defaultValue: null },
        carpetAreaSqft: { type: DataTypes.DECIMAL(10, 3), allowNull: true, defaultValue: null },
        builtUpAreaSqft: { type: DataTypes.DECIMAL(10, 3), allowNull: true, defaultValue: null },
        superBuiltUpAreaSqft: { type: DataTypes.DECIMAL(10, 3), allowNull: true, defaultValue: null },
        areaSqft: { type: DataTypes.DECIMAL(10, 3), allowNull: true, defaultValue: null },
        undividedSharePct: { type: DataTypes.DECIMAL(9, 4), allowNull: true, defaultValue: null },
        isBillable: { type: DataTypes.BOOLEAN, allowNull: false, defaultValue: true },
        possessionDate: { type: DataTypes.DATEONLY, allowNull: true, defaultValue: null },
        notes: { type: DataTypes.STRING(500), allowNull: true, defaultValue: null },
        status: { type: DataTypes.STRING(10), allowNull: false, defaultValue: 'ACTIVE' },
        archivedAt: dateColumn(),
        archivedReason: { type: DataTypes.STRING(300), allowNull: true, defaultValue: null },
        archivedBy: fkColumn(true),
        version: { type: DataTypes.INTEGER.UNSIGNED, allowNull: false, defaultValue: 1 },
        createdBy: fkColumn(true),
        updatedBy: fkColumn(true),
        ...timestampColumns,
      },
      { sequelize, tableName: 'units' },
    );
  }
}
