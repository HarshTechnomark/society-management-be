import {
  DataTypes,
  Model,
  type CreationOptional,
  type InferAttributes,
  type InferCreationAttributes,
  type Sequelize,
} from 'sequelize';
import { fkColumn, idColumn, timestampColumns } from './_columns';

export const LINK_RELATIONS = ['OWNER', 'CO_OWNER', 'TENANT', 'FAMILY', 'CARETAKER'] as const;
export type LinkRelation = (typeof LINK_RELATIONS)[number];
export const FAMILY_RELATIONS = [
  'SPOUSE',
  'CHILD',
  'PARENT',
  'SIBLING',
  'GRANDPARENT',
  'GRANDCHILD',
  'RELATIVE',
  'OTHER',
] as const;
export type FamilyRelation = (typeof FAMILY_RELATIONS)[number];
export const LINK_END_REASONS = [
  'MOVED_OUT',
  'SOLD',
  'TRANSFERRED',
  'TENANCY_ENDED',
  'TERMINATED',
  'DECEASED',
  'CORRECTION',
  'REMOVED',
  'OTHER',
] as const;
export type LinkEndReason = (typeof LINK_END_REASONS)[number];

/** Module 09 section 7.2: one row per period a resident is connected to a unit. Not paranoid. The slot columns are generated by MySQL. */
export class UnitResident extends Model<
  InferAttributes<UnitResident>,
  InferCreationAttributes<UnitResident>
> {
  declare id: CreationOptional<number>;
  declare societyId: number;
  declare unitId: number;
  declare residentId: number;
  declare relation: LinkRelation;
  declare familyRelation: FamilyRelation | null;
  declare sharePercent: string | null;
  declare isPrimary: boolean;
  declare isResiding: boolean;
  declare canLogin: boolean;
  declare tenancyId: number | null;
  declare ownershipTransferId: number | null;
  declare fromDate: string;
  declare toDate: string | null;
  declare endReason: LinkEndReason | null;
  declare endNote: string | null;
  declare source: string;
  declare version: number;
  declare createdBy: number | null;
  declare updatedBy: number | null;
  declare createdAt: CreationOptional<Date>;
  declare updatedAt: CreationOptional<Date>;

  static initModel(sequelize: Sequelize): void {
    UnitResident.init(
      {
        id: idColumn,
        societyId: fkColumn(false),
        unitId: fkColumn(false),
        residentId: fkColumn(false),
        relation: { type: DataTypes.STRING(12), allowNull: false },
        familyRelation: { type: DataTypes.STRING(12), allowNull: true, defaultValue: null },
        sharePercent: { type: DataTypes.DECIMAL(9, 4), allowNull: true, defaultValue: null },
        isPrimary: { type: DataTypes.BOOLEAN, allowNull: false, defaultValue: false },
        isResiding: { type: DataTypes.BOOLEAN, allowNull: false, defaultValue: true },
        canLogin: { type: DataTypes.BOOLEAN, allowNull: false, defaultValue: true },
        tenancyId: fkColumn(true),
        ownershipTransferId: fkColumn(true),
        fromDate: { type: DataTypes.DATEONLY, allowNull: false },
        toDate: { type: DataTypes.DATEONLY, allowNull: true, defaultValue: null },
        endReason: { type: DataTypes.STRING(16), allowNull: true, defaultValue: null },
        endNote: { type: DataTypes.STRING(300), allowNull: true, defaultValue: null },
        source: { type: DataTypes.STRING(20), allowNull: false, defaultValue: 'ADMIN' },
        version: { type: DataTypes.INTEGER.UNSIGNED, allowNull: false, defaultValue: 1 },
        createdBy: fkColumn(true),
        updatedBy: fkColumn(true),
        ...timestampColumns,
      },
      { sequelize, tableName: 'unit_residents' },
    );
  }
}
