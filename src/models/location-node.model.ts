import {
  DataTypes,
  Model,
  type CreationOptional,
  type InferAttributes,
  type InferCreationAttributes,
  type Sequelize,
} from 'sequelize';
import { dateColumn, fkColumn, idColumn, timestampColumns } from './_columns';

export const LOCATION_NODE_TYPES = ['BUILDING', 'FLOOR', 'AREA'] as const;
export type LocationNodeType = (typeof LOCATION_NODE_TYPES)[number];
export const AREA_TYPES = [
  'LOBBY',
  'LIFT',
  'STAIRCASE',
  'CORRIDOR',
  'TERRACE',
  'BASEMENT_PARKING',
  'OPEN_PARKING',
  'GARDEN',
  'PLAYGROUND',
  'GYM',
  'POOL',
  'CLUBHOUSE',
  'HALL',
  'PUMP_ROOM',
  'STP',
  'WTP',
  'ELECTRICAL_ROOM',
  'DG_ROOM',
  'METER_ROOM',
  'WATER_TANK',
  'GARBAGE_AREA',
  'SECURITY_CABIN',
  'GATE',
  'OFFICE',
  'OTHER',
] as const;
export type AreaType = (typeof AREA_TYPES)[number];

/** Module 08 section 7.6. `parentKey` and `activeNameKey` are generated by MySQL and not mapped here. */
export class LocationNode extends Model<
  InferAttributes<LocationNode>,
  InferCreationAttributes<LocationNode>
> {
  declare id: CreationOptional<number>;
  declare societyId: number;
  declare parentId: number | null;
  declare nodeType: LocationNodeType;
  declare areaType: AreaType | null;
  declare name: string;
  declare buildingId: number | null;
  declare floor: number | null;
  declare path: string;
  declare depth: number;
  declare sortOrder: number;
  declare qrToken: string;
  declare status: 'ACTIVE' | 'ARCHIVED';
  declare archivedAt: Date | null;
  declare notes: string | null;
  declare version: number;
  declare createdBy: number | null;
  declare updatedBy: number | null;
  declare createdAt: Date | undefined;
  declare updatedAt: Date | undefined;

  static initModel(sequelize: Sequelize): void {
    LocationNode.init(
      {
        id: idColumn,
        societyId: fkColumn(false),
        parentId: fkColumn(true),
        nodeType: { type: DataTypes.STRING(10), allowNull: false },
        areaType: { type: DataTypes.STRING(20), allowNull: true, defaultValue: null },
        name: { type: DataTypes.STRING(80), allowNull: false },
        buildingId: fkColumn(true),
        floor: { type: DataTypes.SMALLINT, allowNull: true, defaultValue: null },
        path: { type: DataTypes.STRING(100), allowNull: false },
        depth: { type: DataTypes.TINYINT.UNSIGNED, allowNull: false },
        sortOrder: { type: DataTypes.SMALLINT.UNSIGNED, allowNull: false, defaultValue: 0 },
        qrToken: { type: DataTypes.CHAR(12), allowNull: false },
        status: { type: DataTypes.STRING(10), allowNull: false, defaultValue: 'ACTIVE' },
        archivedAt: dateColumn(),
        notes: { type: DataTypes.STRING(300), allowNull: true, defaultValue: null },
        version: { type: DataTypes.INTEGER.UNSIGNED, allowNull: false, defaultValue: 1 },
        createdBy: fkColumn(true),
        updatedBy: fkColumn(true),
        ...timestampColumns,
      },
      { sequelize, tableName: 'location_nodes' },
    );
  }
}
